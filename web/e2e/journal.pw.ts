import { test, expect } from '@playwright/test';

test('account, private journal, explicit sharing, preferences and mobile logout', async ({ page }) => {
  const publicText = `A public little hello. ${Date.now()}`;
  await page.goto('/');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.getByLabel('Username', { exact: true }).fill(`web_${Date.now()}`);
  await page.getByLabel('Nickname', { exact: true }).fill('Web friend');
  await page.getByLabel('Password', { exact: true }).fill('test-password-123');
  await page.getByLabel('Date of birth', { exact: true }).fill('2000-01-01');
  await page.getByRole('button', { name: 'Create your space' }).click();
  await expect(page.getByRole('dialog', { name: 'A little guide to Dearly' })).toBeVisible();
  await page.getByRole('button', { name: 'Maybe later', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Make room for your thoughts.' })).toBeVisible();
  await expect(page.getByRole('status')).toHaveText('A little more connected');
  await page.getByRole('button', { name: 'New entry', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Title', { exact: true }).fill('A small beginning');
  await dialog.getByLabel('Your words', { exact: true }).fill(`Private thoughts. ${publicText}`);
  await expect(dialog.getByLabel('Who can read this?')).toHaveValue('privateOnly');
  await dialog.getByRole('button', { name: 'Save privately' }).click();
  await expect(dialog).not.toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: /A small beginning/ }).click();
  await dialog.getByLabel('Who can read this?').selectOption('community');
  await dialog.getByLabel('Share the entire entry').uncheck();
  await dialog.getByLabel('Passage to share').fill(publicText);
  await expect(dialog.getByLabel('Post anonymously')).toBeChecked();
  await dialog.getByRole('button', { name: 'Save & share' }).click();
  await page.getByRole('link', { name: /Community/ }).click();
  await expect(page.locator('.post-body').filter({ hasText: publicText })).toHaveText(publicText);
  await expect(page.locator('.post-body').filter({ hasText: publicText })).not.toContainText('Private thoughts.');
  await page.getByRole('combobox', { name: 'Language', exact: true }).selectOption('vi');
  await expect(page.getByRole('heading', { name: 'Ở đây luôn có chỗ cho bạn.' })).toBeVisible();
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('lang', 'vi');
  await page.getByRole('combobox', { name: 'Ngôn ngữ', exact: true }).selectOption('en');
  await page.getByRole('button', { name: 'Dark appearance', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.getByRole('button', { name: 'Account settings', exact: true }).click();
  await page.locator('main').getByRole('button', { name: 'Log out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible();
});
